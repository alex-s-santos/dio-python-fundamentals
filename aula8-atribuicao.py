numero = 10;
outro_numero = 25;


numero += 2; #Atribuição com soma
print(numero);

outro_numero -= 3; #Atribuição com subtração
print(outro_numero);

outro_numero *= outro_numero; #Atribuição com multiplicação
print(outro_numero);

outro_numero /= 2; #Atribuição com divisão real
print(outro_numero);

outro_numero //= 2; #Atribuição com divisão exata
print(outro_numero);

outro_numero %= numero; #Atribuição com divisão modular
print(outro_numero);

numero **= numero; #Atribuição com exponenciação
print(numero);